def set_font(run, name='宋体', size=12, bold=False):
    run.font.name = 'Times New Roman'
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.color.rgb = RGBColor(0, 0, 0)
    r = run._element
    r.rPr.rFonts.set(qn('w:eastAsia'), name)


doc = docx.Document()
for style, text in CONTENT:
    p = doc.add_paragraph()
    if style == 'h':
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER if text.startswith('【') else WD_ALIGN_PARAGRAPH.LEFT
        p.paragraph_format.space_before = Pt(10)
        p.paragraph_format.space_after = Pt(6)
        set_font(p.add_run(text), name='黑体', size=14 if text.startswith('【') else 12, bold=True)
    else:
        p.paragraph_format.first_line_indent = Pt(24)
        p.paragraph_format.line_spacing = 1.5
        p.paragraph_format.space_after = Pt(3)
        set_font(p.add_run(text), name='宋体', size=12)

